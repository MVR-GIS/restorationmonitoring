test_that('workshop and hypothesis mappings remain traceable and guard mismatches', {
  skip_if_not_installed('DBI'); skip_if_not_installed('duckdb')
  root <- normalizePath(test_path('..','..'),winslash='/')
  original <- file.path(root,'dev/outputs/duckdb/restoration-research-aligned-v5.duckdb')
  skip_if_not(file.exists(original),'Local aligned prototype unavailable')
  copy <- tempfile(fileext='.duckdb')
  source(file.path(root,'dev/scripts/duckdb-copy-checkpoint.R'),local=TRUE)
  copy_checkpointed_database(original,copy)
  on.exit(unlink(copy),add=TRUE)
  con <- DBI::dbConnect(duckdb::duckdb(),dbdir=copy)
  on.exit(DBI::dbDisconnect(con,shutdown=TRUE),add=TRUE)
  env <- new.env(parent=globalenv())
  sys.source(file.path(root,'dev/scripts/duckdb-multi-report-lib.R'),envir=env)
  expect_equal(DBI::dbGetQuery(con,'SELECT count(*) n FROM workshop_question_model')$n,49)
  expect_equal(DBI::dbGetQuery(con,'SELECT count(*) n FROM workshop_rank_model')$n,196)
  expect_equal(DBI::dbGetQuery(con,'SELECT count(*) n FROM rf.import_layer')$n,27)
  expect_equal(DBI::dbGetQuery(con,'SELECT sum(imported_count) n FROM rf.import_layer')$n,6259)
  expect_equal(DBI::dbGetQuery(con,"SELECT question_id FROM workshop_question_model WHERE workshop_question_id='WQ-39'")$question_id,1L)
  expect_equal(DBI::dbGetQuery(con,'SELECT assertion_id FROM proposed_hypothesis_science')$assertion_id,'SC-08')
  expect_equal(DBI::dbGetQuery(con,'SELECT count(*) n FROM research_alignment_issues')$n,0)
  expect_equal(DBI::dbGetQuery(con,"SELECT count(*) n FROM research_register.assertion_derivation WHERE assertion_id='SC-08'")$n,2)
  expect_equal(DBI::dbGetQuery(con,'SELECT count(*) n FROM objective_criterion_path WHERE objective_id=3 AND criterion_id=1')$n,1)
  for (kind in c('question','survey','project')) {
    report <- env$duckdb_multi_summary(con,kind,1)
    expect_equal(report$feature_source,'geopackage')
    expect_equal(nrow(report$features),7L)
    expect_equal(report$questions$relation_status,'assistant-proposed')
  }
  DBI::dbExecute(con,"INSERT INTO source_document VALUES (900, 'Synthetic journal article', 'journal article')")
  DBI::dbExecute(con,"INSERT INTO source_version VALUES (900, 900, 'test edition', 'synthetic-hash', NULL)")
  DBI::dbExecute(con,"INSERT INTO source_passage VALUES (900, 900, 'synthetic page 2', NULL)")
  DBI::dbExecute(con,"INSERT INTO research_question VALUES (900, 'Synthetic journal research question?', 'journal article', 900, 'source-reported')")
  DBI::dbExecute(con,"INSERT INTO hypothesis VALUES (900, 'Synthetic journal hypothesis', 'journal article', 900, 'source-reported')")
  DBI::dbExecute(con,"INSERT INTO question_source VALUES (900, 900, 'documented in', 'synthetic author', 'source-reported', NULL), (900, 1, 'later related context', 'test', 'assistant-proposed', 'synthetic only')")
  DBI::dbExecute(con,"INSERT INTO hypothesis_source VALUES (900, 900, 'documented in', 'synthetic author', 'source-reported', NULL)")
  DBI::dbExecute(con,"INSERT INTO question_project_link VALUES (900, 900, 1, 'proposed relevance', 900, 'test', 'assistant-proposed', 'synthetic only')")
  DBI::dbExecute(con,"INSERT INTO question_hypothesis VALUES (900, 900, 900, 'source-reported', 900, 'test', 'source-reported', 'synthetic only')")
  DBI::dbExecute(con,"INSERT INTO question_study VALUES (900, 900, 1, 'proposed relevance', 900, 'test', 'assistant-proposed', 'synthetic only')")
  report <- env$duckdb_multi_summary(con,'question',900)
  expect_equal(report$start$description,'Synthetic journal research question?')
  expect_equal(report$projects$native_id,'65')
  expect_true(any(report$hypotheses$hypothesis_text=='Synthetic journal hypothesis'))
  expect_equal(nrow(DBI::dbGetQuery(con,'SELECT * FROM workshop_question_model WHERE question_id=900')),0L)
  expect_equal(DBI::dbGetQuery(con,'SELECT count(*) n FROM question_source WHERE question_id=900')$n,2)
  expect_equal(DBI::dbGetQuery(con,'SELECT record_status FROM question_project_link WHERE link_id=900')$record_status,'assistant-proposed')
  DBI::dbExecute(con,"UPDATE research_question SET question_text='edited without reconciliation' WHERE question_id=1")
  expect_error(env$duckdb_multi_summary(con,'question',1),'identity or wording mismatch')
})
