test_that('DuckDB prototype preserves evidence, optional records and relational integrity', {
  skip_if_not_installed('DBI')
  skip_if_not_installed('duckdb')
  root <- normalizePath(test_path('..', '..'), winslash = '/')
  helper <- file.path(root, 'dev/scripts/duckdb-prototype-lib.R')
  skip_if_not(file.exists(helper), 'Development prototype is not included in package builds')
  env <- new.env(parent = globalenv())
  sys.source(helper, envir = env)
  con <- DBI::dbConnect(duckdb::duckdb(), dbdir = ':memory:')
  on.exit(DBI::dbDisconnect(con, shutdown = TRUE), add = TRUE)
  env$prototype_init(con, file.path(root, 'dev/schemas/duckdb-mvp.sql'))
  env$prototype_seed(con, file.path(root, 'dev/goals'))

  expect_equal(DBI::dbGetQuery(con, 'SELECT COUNT(*) AS n FROM monitoring_task_ref')$n, 0)
  expect_equal(DBI::dbGetQuery(con, 'SELECT COUNT(*) AS n FROM project_objective WHERE emma_objective_ref_id IS NOT NULL')$n, 0)
  expect_equal(DBI::dbGetQuery(con, 'SELECT COUNT(*) AS n FROM project_objective WHERE project_ref_id IS NOT NULL')$n, 0)
  expect_equal(DBI::dbGetQuery(con, 'SELECT record_status FROM assessment')$record_status, 'hypothetical')
  expect_equal(DBI::dbGetQuery(con, 'SELECT record_status FROM decision')$record_status, 'hypothetical')
  expect_match(DBI::dbGetQuery(con, 'SELECT finding_text FROM finding_version')$finding_text, '40 live mussels')
  expect_equal(DBI::dbGetQuery(con, 'SELECT locator FROM source_passage WHERE passage_id = 2')$locator, 'printed p. 7; PDF p. 8')
  path <- DBI::dbGetQuery(con, 'SELECT relation_status, scope_note, finding_text, source_locator FROM question_finding_path')
  expect_equal(nrow(path), 1L)
  expect_equal(path$relation_status, 'assistant-proposed')
  expect_match(path$scope_note, 'Not evidence')
  expect_equal(path$source_locator, 'printed p. 7; PDF p. 8')
  expect_equal(nrow(DBI::dbGetQuery(con, 'SELECT * FROM objective_criterion_path')), 1L)
  expect_equal(DBI::dbGetQuery(con, 'SELECT source_passage_id FROM study_event')$source_passage_id, 6L)
  DBI::dbExecute(con, "INSERT INTO research_question (question_id,question_text,origin_kind,record_status) VALUES (99,'Synthetic independent question','test','hypothetical')")
  DBI::dbExecute(con, "INSERT INTO decision (decision_id,decision_text,decision_type,record_status) VALUES (99,'Synthetic independent decision','deferral','hypothetical')")
  expect_equal(DBI::dbGetQuery(con, 'SELECT COUNT(*) AS n FROM question_study WHERE question_id=99')$n, 0)
  expect_equal(DBI::dbGetQuery(con, 'SELECT COUNT(*) AS n FROM assessment_decision WHERE decision_id=99')$n, 0)
  expect_error(DBI::dbExecute(con, 'INSERT INTO objective_criterion (objective_id, criterion_id) VALUES (999, 1)'), 'foreign key|violates', ignore.case = TRUE)
  expect_error(DBI::dbExecute(con, 'INSERT INTO objective_criterion (objective_id, criterion_id) VALUES (3, 1)'), 'duplicate|unique|primary key', ignore.case = TRUE)
  expect_error(env$prototype_init(con, file.path(root, 'dev/schemas/duckdb-mvp.sql')), 'not empty')
})

test_that('objective and task junctions support many-to-many links', {
  skip_if_not_installed('DBI')
  skip_if_not_installed('duckdb')
  root <- normalizePath(test_path('..', '..'), winslash = '/')
  helper <- file.path(root, 'dev/scripts/duckdb-prototype-lib.R')
  skip_if_not(file.exists(helper), 'Development prototype is not included in package builds')
  env <- new.env(parent = globalenv())
  sys.source(helper, envir = env)
  con <- DBI::dbConnect(duckdb::duckdb(), dbdir = ':memory:')
  on.exit(DBI::dbDisconnect(con, shutdown = TRUE), add = TRUE)
  env$prototype_init(con, file.path(root, 'dev/schemas/duckdb-mvp.sql'))
  env$prototype_seed(con, file.path(root, 'dev/goals'))
  DBI::dbExecute(con, "INSERT INTO project_objective (objective_id,objective_text,record_status) VALUES (91,'Synthetic objective A','hypothetical'),(92,'Synthetic objective B','hypothetical')")
  DBI::dbExecute(con, "INSERT INTO performance_criterion (criterion_id,criterion_text,record_status) VALUES (91,'Synthetic criterion A','hypothetical'),(92,'Synthetic criterion B','hypothetical')")
  DBI::dbExecute(con, 'INSERT INTO objective_criterion (objective_id,criterion_id) VALUES (91,91),(91,92),(92,91)')
  DBI::dbExecute(con, "INSERT INTO external_reference VALUES (91,1,'task','synthetic','task-a'),(92,1,'task','synthetic','task-b')")
  DBI::dbExecute(con, 'INSERT INTO monitoring_task_ref VALUES (91,91),(92,92)')
  DBI::dbExecute(con, 'INSERT INTO task_criterion (monitoring_task_ref_id,criterion_id) VALUES (91,91),(91,92),(92,91)')
  expect_equal(DBI::dbGetQuery(con, 'SELECT COUNT(*) AS n FROM objective_criterion WHERE objective_id >= 91')$n, 3)
  expect_equal(DBI::dbGetQuery(con, 'SELECT COUNT(*) AS n FROM task_criterion')$n, 3)
})
