test_that('question report follows database changes and keeps hypothetical records opt-in', {
  skip_if_not_installed('DBI')
  skip_if_not_installed('duckdb')
  root <- normalizePath(test_path('..', '..'), winslash='/')
  seed <- file.path(root, 'dev/scripts/duckdb-prototype-lib.R')
  reader <- file.path(root, 'dev/scripts/duckdb-report-lib.R')
  skip_if_not(file.exists(seed) && file.exists(reader), 'Development prototype is not included in package builds')
  env <- new.env(parent=globalenv())
  sys.source(seed, envir=env)
  sys.source(reader, envir=env)
  con <- DBI::dbConnect(duckdb::duckdb(), dbdir=':memory:')
  on.exit(DBI::dbDisconnect(con, shutdown=TRUE), add=TRUE)
  env$prototype_init(con, file.path(root, 'dev/schemas/duckdb-mvp.sql'))
  env$prototype_seed(con, file.path(root, 'dev/goals'))
  result <- env$duckdb_question_summary(con, 1)
  expect_equal(nrow(result$findings), 1L)
  expect_equal(result$findings$relation_status, 'assistant-proposed')
  expect_match(result$findings$scope_note, 'Not evidence')
  expect_equal(result$findings$source_locator, 'printed p. 7; PDF p. 8')
  expect_equal(nrow(result$assessments), 0L)
  example <- env$duckdb_question_summary(con, 1, TRUE)
  expect_equal(example$assessments$record_status, 'hypothetical')
  DBI::dbExecute(con, "UPDATE finding_version SET finding_text='Changed test finding' WHERE finding_version_id=1")
  expect_equal(env$duckdb_question_summary(con, 1)$findings$finding_text, 'Changed test finding')
  DBI::dbExecute(con, 'DELETE FROM question_study WHERE link_id=1')
  expect_equal(nrow(env$duckdb_question_summary(con, 1)$findings), 0L)
  expect_error(env$duckdb_question_summary(con, 999), 'not found')
})
