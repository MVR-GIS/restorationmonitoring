test_that('UMRR-DB project snapshot matches its GeoPackage and retains earlier prototype data', {
  skip_if_not_installed('DBI'); skip_if_not_installed('duckdb'); skip_if_not_installed('digest')
  root <- normalizePath(test_path('..','..'),winslash='/')
  db <- file.path(root,'dev/outputs/duckdb/restoration-umrrdb-projects-v1.duckdb')
  gpkg <- file.path(root,'..','UMRR','UMRR-DB','UMRRDB_Projects_20261106.gpkg')
  ext <- file.path(root,'dev/outputs/duckdb-extensions')
  skip_if_not(file.exists(db) && file.exists(gpkg) && dir.exists(ext),'Local export, database or spatial extension unavailable')
  con <- DBI::dbConnect(duckdb::duckdb(),dbdir=db,read_only=TRUE)
  on.exit(DBI::dbDisconnect(con,shutdown=TRUE),add=TRUE)
  DBI::dbExecute(con,paste0('SET extension_directory=',DBI::dbQuoteString(con,normalizePath(ext,winslash='/'))))
  tryCatch(DBI::dbExecute(con,'LOAD spatial'),error=function(e) skip('Spatial extension unavailable for this DuckDB version'))
  info <- DBI::dbGetQuery(con,'SELECT * FROM umrrdb.import_layer')
  expect_equal(info$layer_name,'Projects'); expect_equal(as.numeric(info$imported_count),140)
  expect_equal(info$crs_authority,'EPSG'); expect_equal(info$crs_code,'26915')
  expect_equal(DBI::dbGetQuery(con,'SELECT source_sha256 FROM umrrdb.import_source')$source_sha256,
               digest::digest(file=gpkg,algo='sha256',serialize=FALSE))
  path <- as.character(DBI::dbQuoteString(con,normalizePath(gpkg,winslash='/')))
  src <- paste0("SELECT * FROM ST_Read(",path,", layer='Projects')")
  dst <- 'SELECT * FROM umrrdb.src_Projects'
  diff <- DBI::dbGetQuery(con,paste0('SELECT (SELECT count(*) FROM (',src,' EXCEPT ALL ',dst,')) + (SELECT count(*) FROM (',dst,' EXCEPT ALL ',src,')) AS n'))
  expect_equal(as.numeric(diff$n),0)
  checks <- DBI::dbGetQuery(con,'SELECT count(*) n,count(DISTINCT PROJECT_ID) ids,count(*) FILTER(WHERE SHAPE IS NULL) missing_geometry FROM umrrdb.src_Projects')
  expect_equal(as.numeric(checks$n),140); expect_equal(as.numeric(checks$ids),140); expect_equal(as.numeric(checks$missing_geometry),15)
  expect_equal(DBI::dbGetQuery(con,'SELECT PROJECT_NAME_SHORT FROM umrrdb.src_Projects WHERE PROJECT_ID=65')$PROJECT_NAME_SHORT,'Bertom McCartney Lakes')
  expect_equal(as.numeric(DBI::dbGetQuery(con,'SELECT sum(imported_count) n FROM rf.import_layer')$n),6259)
  expect_equal(as.numeric(DBI::dbGetQuery(con,'SELECT count(*) n FROM research_register.study_evidence_component')$n),10)
  expect_equal(as.numeric(DBI::dbGetQuery(con,'SELECT count(*) n FROM plan_reconciliation_issues')$n),0)
})
