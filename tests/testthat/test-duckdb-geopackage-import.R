test_that('complete GeoPackage snapshots retain layers, counts and source provenance', {
  skip_if_not_installed('DBI'); skip_if_not_installed('duckdb')
  skip_if_not_installed('digest'); skip_if_not_installed('sf')
  root <- normalizePath(test_path('..','..'), winslash='/')
  ext <- file.path(root,'dev','outputs','duckdb-extensions')
  skip_if_not(dir.exists(ext), 'Local spatial extension unavailable')
  con <- DBI::dbConnect(duckdb::duckdb(), dbdir=':memory:')
  on.exit(DBI::dbDisconnect(con, shutdown=TRUE), add=TRUE)
  DBI::dbExecute(con, paste0('SET extension_directory=', DBI::dbQuoteString(con, normalizePath(ext,winslash='/'))))
  tryCatch(DBI::dbExecute(con, 'LOAD spatial'), error=function(e) skip('Spatial extension unavailable for this version'))
  source(file.path(root,'dev/scripts/duckdb-geopackage-import-lib.R'), local=TRUE)
  path <- tempfile(fileext='.gpkg'); on.exit(unlink(path), add=TRUE)
  geom <- sf::st_sfc(sf::st_point(c(-91,43)), sf::st_point(c(-92,44)), crs=4326)
  sf::st_write(sf::st_sf(PROJECT_ID=c(65L,66L),geometry=geom), path, layer='Projects', quiet=TRUE)
  sf::st_write(sf::st_sf(id=1L, geometry=geom[1]), path, layer='Other', append=FALSE, quiet=TRUE)
  result <- import_geopackage_snapshot(con, path, 'rf')
  expect_equal(nrow(result),2L)
  expect_equal(sort(as.numeric(result$imported_count)),c(1,2))
  expect_equal(DBI::dbGetQuery(con,'SELECT count(*) n FROM rf."src_Projects"')$n,2)
  expect_equal(DBI::dbGetQuery(con,'SELECT count(*) n FROM rf."src_Projects" WHERE geom IS NOT NULL')$n,2)
  expect_equal(DBI::dbGetQuery(con,'SELECT source_sha256 FROM rf.import_source')$source_sha256,
    digest::digest(file=path, algo='sha256', serialize=FALSE))
  expect_true(all(DBI::dbGetQuery(con,'SELECT crs_code FROM rf.import_layer')$crs_code=='4326'))
  expect_error(import_geopackage_snapshot(con,path,'rf'),'already exists')
  expect_error(import_geopackage_snapshot(con,path,'umrrdb',layers='Missing'),'not found')
  one <- import_geopackage_snapshot(con,path,'umrrdb',layers='Projects')
  expect_equal(one$layer,'Projects')
  expect_equal(DBI::dbGetQuery(con,'SELECT count(*) n FROM umrrdb.import_layer')$n,1)
})
