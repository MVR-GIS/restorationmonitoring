test_that('Steamboat candidate mappings preserve differences and detect drift', {
  skip_if_not_installed('DBI'); skip_if_not_installed('duckdb')
  root <- normalizePath(test_path('..','..'),winslash='/')
  db <- file.path(root,'dev/outputs/duckdb/restoration-steamboat-reconciled-v1.duckdb')
  skip_if_not(file.exists(db),'Local reconciled development database unavailable')
  source(file.path(root,'dev/scripts/duckdb-copy-checkpoint.R'),local=TRUE)
  copy <- tempfile(fileext='.duckdb'); copy_checkpointed_database(db,copy)
  on.exit(unlink(copy),add=TRUE)
  con <- DBI::dbConnect(duckdb::duckdb(),dbdir=copy)
  on.exit(DBI::dbDisconnect(con,shutdown=TRUE),add=TRUE)
  env <- new.env(parent=globalenv()); sys.source(file.path(root,'dev/scripts/duckdb-steamboat-report-lib.R'),envir=env)
  r <- env$steamboat_duckdb_summary(con)
  expect_equal(r$objective_reconciliation$plan_objective_id,'SI-O3')
  expect_equal(r$criterion_reconciliation$plan_criterion_id,'SI-C04')
  expect_equal(r$objective_reconciliation$record_status,'analyst-proposed')
  expect_match(r$objective_reconciliation$scope_note,'1950s')
  expect_match(r$objective_reconciliation$worksheet_text,'1950s')
  expect_false(grepl('1950s',r$objective_reconciliation$prototype_text))
  expect_equal(DBI::dbGetQuery(con,'SELECT count(*) n FROM plan_reconciliation_issues')$n,0)
  expect_equal(nrow(r$objectives),4L); expect_equal(nrow(r$criteria),11L); expect_equal(nrow(r$chain),10L)
  DBI::dbExecute(con,"UPDATE research_register.plan_objective SET normalized_text='Changed without review' WHERE objective_id='SI-O3'")
  expect_error(env$steamboat_duckdb_summary(con),'reconciliation requires review')
})
