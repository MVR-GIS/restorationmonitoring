test_that('three entry points expose the same bounded paths and qualifications', {
  skip_if_not_installed('DBI'); skip_if_not_installed('duckdb')
  root <- normalizePath(test_path('..','..'), winslash='/')
  seed <- file.path(root,'dev/scripts/duckdb-prototype-lib.R')
  reader <- file.path(root,'dev/scripts/duckdb-multi-report-lib.R')
  skip_if_not(file.exists(seed) && file.exists(reader), 'Development files not in package build')
  env <- new.env(parent=globalenv()); sys.source(seed,envir=env); sys.source(reader,envir=env)
  con <- DBI::dbConnect(duckdb::duckdb(), dbdir=':memory:')
  on.exit(DBI::dbDisconnect(con, shutdown=TRUE), add=TRUE)
  env$prototype_init(con,file.path(root,'dev/schemas/duckdb-mvp.sql'))
  env$prototype_seed(con,file.path(root,'dev/goals'))
  views <- lapply(c('question','survey','project'), function(type) env$duckdb_multi_summary(con,type,1))
  for (x in views) {
    expect_equal(x$findings$finding_version_id, 1L)
    expect_equal(x$questions$relation_status, 'assistant-proposed')
    expect_equal(x$projects$review_state, 'candidate')
    expect_equal(x$objectives$objective_id, c(1L,2L))
    expect_true(all(x$objectives$objective_relation_status == 'assistant-proposed'))
    expect_equal(x$findings$source_locator, 'printed p. 7; PDF p. 8')
    expect_equal(nrow(x$assessments), 0L)
    expect_null(x$project_snapshot)
  }
  DBI::dbExecute(con,'CREATE SCHEMA umrrdb')
  DBI::dbExecute(con,'CREATE TABLE umrrdb.src_Projects (PROJECT_ID INTEGER, PROJECT_NAME_SHORT VARCHAR, DISTRICT VARCHAR, POOL VARCHAR, PHASE VARCHAR, STATUS VARCHAR, COMPLETION_DATE DATE, SHAPE VARCHAR)')
  DBI::dbExecute(con,"INSERT INTO umrrdb.src_Projects VALUES (65,'Synthetic project','MVR','Pool 11','Post Construction','Complete',DATE '1992-06-01',NULL), (66,'Other project','MVR',NULL,NULL,NULL,NULL,'shape')")
  DBI::dbExecute(con,"CREATE TABLE umrrdb.import_source AS SELECT 'test-project-hash' AS source_sha256")
  DBI::dbExecute(con,"CREATE TABLE umrrdb.import_layer AS SELECT 'Projects' AS layer_name, 'EPSG' AS crs_authority, '26915' AS crs_code")
  for (type in c('question','survey','project')) {
    x <- env$duckdb_multi_summary(con,type,1)
    expect_equal(nrow(x$project_snapshot),1L)
    expect_equal(x$project_snapshot$project_id,65L)
    expect_equal(x$project_snapshot$geometry_status,'Missing in source')
    expect_equal(x$project_snapshot$source_sha256,'test-project-hash')
  }
  DBI::dbExecute(con,"INSERT INTO external_system VALUES (20,'Other system')")
  DBI::dbExecute(con,"INSERT INTO external_reference VALUES (20,20,'project','Other.Projects','65')")
  expect_equal(nrow(env$duckdb_multi_summary(con,'project',20)$project_snapshot),0L)
  expect_equal(env$duckdb_multi_summary(con,'project',1,TRUE)$assessments$record_status,'hypothetical')
  expect_error(env$duckdb_multi_summary(con,'survey',999),'not found')
  expect_error(env$duckdb_multi_summary(con,'invalid',1),'Unknown')
  DBI::dbExecute(con, 'DELETE FROM study_link_passage WHERE link_id=1')
  DBI::dbExecute(con, 'DELETE FROM study_external_link WHERE link_id=1')
  x <- env$duckdb_multi_summary(con,'project',1)
  expect_equal(nrow(x$studies),0L)
  expect_equal(x$objectives$objective_id,c(1L,2L))
  expect_equal(x$project_snapshot$project_name,'Synthetic project')
})
