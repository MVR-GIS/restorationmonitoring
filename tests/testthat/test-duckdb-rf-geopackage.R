test_that('GeoPackage staging preserves spatial provenance and compares IDs without attaching geometry', {
  skip_if_not_installed('duckdb'); skip_if_not_installed('DBI')
  skip_if_not_installed('digest'); skip_if_not_installed('sf')
  root <- normalizePath(test_path('..', '..'), winslash = '/')
  ext <- file.path(root, 'dev', 'outputs', 'duckdb-extensions')
  skip_if_not(dir.exists(ext), 'Local spatial extension unavailable')
  con <- DBI::dbConnect(duckdb::duckdb(), dbdir = ':memory:')
  on.exit(DBI::dbDisconnect(con, shutdown = TRUE), add = TRUE)
  DBI::dbExecute(con, paste0('SET extension_directory=', DBI::dbQuoteString(con, normalizePath(ext, winslash = '/'))))
  tryCatch(DBI::dbExecute(con, 'LOAD spatial'), error = function(e) skip('Spatial extension unavailable for this version'))
  source(file.path(root, 'dev/scripts/duckdb-rf-geopackage-lib.R'), local = TRUE)
  DBI::dbExecute(con, 'CREATE SCHEMA rf')
  DBI::dbExecute(con, 'CREATE TABLE rf.revetment (restorfeatidpk BIGINT, project_id VARCHAR, geometry GEOMETRY)')
  DBI::dbExecute(con, "INSERT INTO rf.revetment VALUES (6723, '65', NULL), (6724, '65', NULL)")
  p <- tempfile(fileext = '.gpkg')
  on.exit(unlink(p), add = TRUE)
  points <- sf::st_sfc(sf::st_point(c(-91, 43)), sf::st_point(c(-91.1, 43.1)),
                       sf::st_point(c(-91.2, 43.2)), crs = 4326)
  x <- sf::st_sf(RESTORFEATIDPK = c(6723, 9999, 6724), PROJECT_ID = c(65, 65, 99), geometry = points)
  sf::st_write(x, p, layer = 'revetment', quiet = TRUE)
  expect_error(rf_stage_geopackage(con, p, 'missing'), 'not found')
  result <- rf_stage_geopackage(con, p, 'revetment')
  expect_equal(as.numeric(result$counts$staged), 2)
  expect_equal(as.numeric(result$unmatched$unmatched_staged), 1)
  expect_equal(as.numeric(result$comparison$staged_matches), c(1, 0))
  expect_equal(result$source$crs_authority, 'EPSG')
  expect_equal(result$source$crs_code, '4326')
  expect_equal(DBI::dbGetQuery(con, 'SELECT count(*) n FROM rf.revetment WHERE geometry IS NOT NULL')$n, 0)
  expect_equal(DBI::dbGetQuery(con, 'SELECT count(*) n FROM rf.geopackage_stage WHERE geom IS NOT NULL')$n, 2)
  expect_equal(DBI::dbGetQuery(con, 'SELECT source_sha256 FROM rf.geopackage_source')$source_sha256,
               digest::digest(file = p, algo = 'sha256', serialize = FALSE))
  expect_error(rf_stage_geopackage(con, p, 'revetment'), 'already exists')
})
