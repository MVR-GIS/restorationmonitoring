test_that('RF snapshot retains seven source records and keeps synthetic geometry isolated', {
  skip_if_not_installed('DBI'); skip_if_not_installed('duckdb'); skip_if_not_installed('xml2'); skip_if_not_installed('digest')
  root <- normalizePath(test_path('..','..'), winslash='/')
  source_file <- file.path(root,'..','UMRR','RestorationFeatures','RestorationSchema_data_20261102.xml')
  ext <- file.path(root,'dev','outputs','duckdb-extensions')
  skip_if_not(file.exists(source_file) && dir.exists(ext), 'Original export or local spatial extension unavailable')
  env <- new.env(parent=globalenv())
  sys.source(file.path(root,'dev/scripts/duckdb-prototype-lib.R'),envir=env)
  sys.source(file.path(root,'dev/scripts/duckdb-rf-lib.R'),envir=env)
  sys.source(file.path(root,'dev/scripts/duckdb-multi-report-lib.R'),envir=env)
  con <- DBI::dbConnect(duckdb::duckdb(),dbdir=':memory:')
  on.exit(DBI::dbDisconnect(con,shutdown=TRUE),add=TRUE)
  DBI::dbExecute(con,paste0('SET extension_directory=',DBI::dbQuoteString(con,normalizePath(ext,winslash='/'))))
  tryCatch(DBI::dbExecute(con,'LOAD spatial'), error=function(e) skip('Spatial extension not available for this DuckDB version'))
  env$prototype_init(con,file.path(root,'dev/schemas/duckdb-mvp.sql'))
  env$prototype_seed(con,file.path(root,'dev/goals'))
  env$rf_import_bertom(con,source_file,file.path(root,'dev/schemas/duckdb-rf-mvp.sql'))
  rows <- DBI::dbGetQuery(con,'SELECT restorfeatidpk, project_id, geometry IS NULL AS missing_geometry FROM rf.revetment ORDER BY restorfeatidpk')
  expect_equal(as.numeric(rows$restorfeatidpk),as.numeric(6723:6729))
  expect_true(all(rows$project_id=='65'))
  expect_true(all(rows$missing_geometry))
  expect_equal(DBI::dbGetQuery(con,'SELECT ST_AsText(geometry) AS wkt FROM rf.spatial_demo')$wkt,'LINESTRING (0 0, 1 1, 2 1)')
  for (type in c('question','survey','project')) {
    report <- env$duckdb_multi_summary(con,type,1)
    expect_equal(nrow(report$features),7L)
    expect_true(all(report$features$source_class=='RESTORATION.Revetment'))
  }
  fake <- tempfile(fileext='.xml'); writeLines('<not-the-supplied-export/>',fake)
  on.exit(unlink(fake),add=TRUE)
  expect_error(env$rf_import_bertom(con,fake,file.path(root,'dev/schemas/duckdb-rf-mvp.sql')),'Unexpected XML version')
})
